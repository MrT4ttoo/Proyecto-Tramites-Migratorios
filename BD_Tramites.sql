/* ======================= NUCLEO MIGRATORIO ======================= */
-- RUEX = identificador logico unico de la PERSONA extranjera (PK). El TRAMITE se identifica
-- con expediente_id (snm.Expediente). Un mismo RUEX puede tener varios expedientes en el tiempo.
-- Un pasaporte (nacionalidad + numero) solo puede pertenecer a un RUEX y un usuario a un solo RUEX.
CREATE TABLE snm.Extranjero(
    ruex VARCHAR(20) NOT NULL CONSTRAINT PK_Extranjero PRIMARY KEY,   -- llave primaria inquebrantable
    usuario_id INT NOT NULL CONSTRAINT UQ_Extranjero_usuario UNIQUE
        CONSTRAINT FK_Extranjero_Usuario REFERENCES seg.Usuario(usuario_id),
    nombres VARCHAR(100) NOT NULL,
    apellidos VARCHAR(100) NOT NULL,
    fecha_nacimiento DATE NOT NULL,
    nacionalidad_id SMALLINT NOT NULL CONSTRAINT FK_Extranjero_Nac REFERENCES cat.Nacionalidad(nacionalidad_id),
    pasaporte_numero VARCHAR(30) NOT NULL,
    telefono VARCHAR(25) NULL,
    creado_en TIMESTAMP(0) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    CONSTRAINT CK_Extranjero_ruex CHECK (length(ruex) > 0 AND ruex ~ '^[A-Za-z0-9-]+$'),
    CONSTRAINT UQ_Extranjero_pasaporte UNIQUE (nacionalidad_id, pasaporte_numero));

