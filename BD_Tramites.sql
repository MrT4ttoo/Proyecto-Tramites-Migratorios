SELECT er.expediente_id, r.requisito_id, r.codigo AS codigo_requisito, r.descripcion,
       r.origen, r.obligatorio, r.orden, er.estado,
       CASE er.estado
            WHEN 'PENDIENTE_CARGA' THEN 'Pendiente de Carga'
            WHEN 'DOCUMENTO_VALIDO' THEN 'Documento Valido'
            WHEN 'DOCUMENTO_VENCIDO' THEN 'Documento Vencido'
            WHEN 'PENDIENTE_VERIFICACION' THEN 'Pendiente de Verificacion'
            WHEN 'VERIFICADO_FUENTE' THEN 'Verificado en Fuente Oficial'
            WHEN 'NO_CUMPLE' THEN 'No Cumple'
            WHEN 'INDISPONIBILIDAD_TECNICA' THEN 'Indisponibilidad Tecnica'
       END AS etiqueta,
       CASE
            WHEN er.estado IN ('DOCUMENTO_VALIDO','VERIFICADO_FUENTE') THEN 'VERDE'
            WHEN er.estado IN ('DOCUMENTO_VENCIDO','NO_CUMPLE') THEN 'ROJO'
            ELSE 'AMARILLO'
       END AS semaforo,
       er.documento_id, er.origen_documento, ent.codigo AS entidad_externa,
       ce.resultado AS resultado_consulta,
       ce.correlation_id AS consulta_correlation_id,
       ce.intentos AS intentos_consulta,
       ce.max_intentos AS max_intentos_consulta
FROM snm.ExpedienteRequisito er
JOIN cat.Requisito r ON r.requisito_id = er.requisito_id
LEFT JOIN cat.ServicioExterno s ON s.servicio_id = r.servicio_id
LEFT JOIN cat.EntidadExterna ent ON ent.entidad_id = s.entidad_id
LEFT JOIN ext.ConsultaExterna ce
       ON ce.expediente_id = er.expediente_id
      AND ce.requisito_id = er.requisito_id;

