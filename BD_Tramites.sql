          AND dd.estado = 'VIGENTE'
          AND (dd.fecha_vencimiento IS NULL OR dd.fecha_vencimiento >= hoy)
        ORDER BY dd.fecha_emision DESC, dd.documento_id DESC
        LIMIT 1
    ) d ON TRUE
    WHERE er.expediente_id = snm.sp_SugerirReutilizacion.expediente_id
      AND er.estado IN ('PENDIENTE_CARGA','DOCUMENTO_VENCIDO');
END;
