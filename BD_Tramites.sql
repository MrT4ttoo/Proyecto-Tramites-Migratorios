CREATE OR REPLACE PROCEDURE aud.sp_RegistrarEvento(
    tipo VARCHAR(30),
    severidad VARCHAR(10) DEFAULT 'INFO',
    usuario_id INTEGER DEFAULT NULL,
    ruex VARCHAR(20) DEFAULT NULL,
    entidad VARCHAR(60) DEFAULT NULL,
    entidad_id VARCHAR(60) DEFAULT NULL,
    ip VARCHAR(45) DEFAULT NULL,
    detalle VARCHAR(1000) DEFAULT NULL
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, cat, seg, priv, snm, ext, aud, met
AS $$
DECLARE
    prev BYTEA;
    fecha TIMESTAMP(3);
    hash BYTEA;
BEGIN
    /* Equivalente de sp_getapplock: bloqueo transaccional exclusivo sobre la cadena. */
    PERFORM pg_advisory_xact_lock(hashtextextended('aud.Bitacora', 0));

    SELECT hash_actual INTO prev
    FROM aud.Bitacora
    ORDER BY bitacora_id DESC
    LIMIT 1;

    IF prev IS NULL THEN
        prev := decode(repeat('00', 32), 'hex');
    END IF;

    fecha := (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')::timestamp(3);
    hash := public.digest(
        convert_to(
            encode(prev, 'hex') || '|' ||
            to_char(fecha, 'YYYY-MM-DD"T"HH24:MI:SS.MS') || '|' ||
            aud.sp_RegistrarEvento.tipo || '|' || aud.sp_RegistrarEvento.severidad || '|' ||
            COALESCE(aud.sp_RegistrarEvento.usuario_id::VARCHAR(12), '') || '|' ||
            COALESCE(aud.sp_RegistrarEvento.ruex, '') || '|' ||
            COALESCE(aud.sp_RegistrarEvento.entidad, '') || '|' ||
            COALESCE(aud.sp_RegistrarEvento.entidad_id, '') || '|' ||
            COALESCE(aud.sp_RegistrarEvento.ip, '') || '|' ||
            COALESCE(aud.sp_RegistrarEvento.detalle, ''),
            'UTF8'
        ),
        'sha256'
    );

    INSERT INTO aud.Bitacora(
        fecha_utc, tipo_evento, severidad, usuario_id, ruex, entidad,
        entidad_id, ip_origen, detalle, hash_previo, hash_actual
    )
    VALUES (
        fecha, aud.sp_RegistrarEvento.tipo, aud.sp_RegistrarEvento.severidad,
        aud.sp_RegistrarEvento.usuario_id, aud.sp_RegistrarEvento.ruex, aud.sp_RegistrarEvento.entidad,
        aud.sp_RegistrarEvento.entidad_id, aud.sp_RegistrarEvento.ip, aud.sp_RegistrarEvento.detalle, prev, hash
    );
END;
$$;

CREATE OR REPLACE PROCEDURE aud.sp_VerificarCadena(OUT resultado REFCURSOR)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, cat, seg, priv, snm, ext, aud, met
AS $$
BEGIN
    /* Sin filas = cadena integra. */
    OPEN resultado FOR
    SELECT bitacora_id AS registro_alterado
    FROM (
        SELECT bitacora_id, hash_previo, hash_actual,
               LAG(hash_actual) OVER (ORDER BY bitacora_id) AS previo_real,
               public.digest(
                   convert_to(
                       encode(hash_previo, 'hex') || '|' ||
                       to_char(fecha_utc, 'YYYY-MM-DD"T"HH24:MI:SS.MS') || '|' ||
                       tipo_evento || '|' || severidad || '|' ||
                       COALESCE(usuario_id::VARCHAR(12), '') || '|' ||
                       COALESCE(ruex, '') || '|' ||
                       COALESCE(entidad, '') || '|' ||
                       COALESCE(entidad_id, '') || '|' ||
                       COALESCE(ip_origen, '') || '|' ||
                       COALESCE(detalle, ''),
                       'UTF8'
                   ),
                   'sha256'
               ) AS recalculado
        FROM aud.Bitacora
    ) x
    WHERE recalculado <> hash_actual
       OR (previo_real IS NOT NULL AND hash_previo <> previo_real);
END;
$$;

