CREATE OR REPLACE PROCEDURE snm.sp_VincularDocumento(
    usuario_id INTEGER, expediente_id BIGINT, requisito_id INTEGER,
    documento_id BIGINT, origen VARCHAR(12) DEFAULT 'CARGA_NUEVA'
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, cat, seg, priv, snm, ext, aud, met
AS $$
DECLARE
    id_txt VARCHAR(20) := expediente_id::VARCHAR(20);
    ruex_exp VARCHAR(20);
    estado_exp SMALLINT;
    tipo_req SMALLINT;
    hoy DATE := (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')::date;
BEGIN
    IF NOT snm.fn_EsDuenoExpediente(snm.sp_VincularDocumento.usuario_id, snm.sp_VincularDocumento.expediente_id) THEN
        CALL aud.sp_RegistrarEvento(
            tipo => 'IDOR', severidad => 'ALTA', usuario_id => usuario_id,
            entidad => 'Expediente', entidad_id => id_txt);
        RAISE EXCEPTION 'Acceso denegado.';
    END IF;

    IF snm.sp_VincularDocumento.origen NOT IN ('CARGA_NUEVA','REUTILIZADO') THEN
        RAISE EXCEPTION 'Origen de documento invalido.';
    END IF;

    SELECT ruex, estado_id
      INTO ruex_exp, estado_exp
    FROM snm.Expediente
    WHERE snm.Expediente.expediente_id = snm.sp_VincularDocumento.expediente_id
    FOR UPDATE;

    IF estado_exp NOT IN (1,3) THEN
        RAISE EXCEPTION 'El expediente no admite cambios en su estado actual.';
    END IF;

    IF NOT priv.fn_ConsentimientoVigente(ruex_exp) THEN
        RAISE EXCEPTION 'Ley 81: consentimiento no vigente.';
    END IF;

    SELECT r.tipo_documento_id INTO tipo_req
    FROM snm.ExpedienteRequisito er
    JOIN cat.Requisito r ON r.requisito_id = er.requisito_id
    WHERE er.expediente_id = snm.sp_VincularDocumento.expediente_id
      AND er.requisito_id = snm.sp_VincularDocumento.requisito_id
      AND r.origen = 'APORTADO';

    IF tipo_req IS NULL THEN
        RAISE EXCEPTION 'El requisito no es documental o no pertenece al expediente.';
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM snm.Documento
        WHERE snm.Documento.documento_id = snm.sp_VincularDocumento.documento_id
          AND ruex = ruex_exp
          AND tipo_documento_id = tipo_req
          AND estado = 'VIGENTE'
          AND (fecha_vencimiento IS NULL OR fecha_vencimiento >= hoy)
    ) THEN
        RAISE EXCEPTION 'Documento inexistente, ajeno, de otro tipo o no vigente.';
    END IF;

    UPDATE snm.ExpedienteRequisito
    SET estado = 'DOCUMENTO_VALIDO',
        documento_id = snm.sp_VincularDocumento.documento_id,
        origen_documento = snm.sp_VincularDocumento.origen,
        actualizado_en = (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
    WHERE snm.ExpedienteRequisito.expediente_id = snm.sp_VincularDocumento.expediente_id
      AND snm.ExpedienteRequisito.requisito_id = snm.sp_VincularDocumento.requisito_id;

    UPDATE snm.Expediente
    SET actualizado_en = (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
    WHERE snm.Expediente.expediente_id = snm.sp_VincularDocumento.expediente_id;

    CALL aud.sp_RegistrarEvento(
        tipo => 'DOCUMENTO_VINCULADO', usuario_id => snm.sp_VincularDocumento.usuario_id,
        ruex => ruex_exp, entidad => 'Expediente',
        entidad_id => id_txt, detalle => snm.sp_VincularDocumento.origen);
END;
$$;

CREATE OR REPLACE PROCEDURE snm.sp_EnviarExpediente(
    usuario_id INTEGER, expediente_id BIGINT
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, cat, seg, priv, snm, ext, aud, met
AS $$
DECLARE
    id_txt VARCHAR(20) := expediente_id::VARCHAR(20);
    ruex_exp VARCHAR(20);
    estado_exp SMALLINT;
    obs VARCHAR(500);
BEGIN
    IF NOT snm.fn_EsDuenoExpediente(snm.sp_EnviarExpediente.usuario_id, snm.sp_EnviarExpediente.expediente_id) THEN
        CALL aud.sp_RegistrarEvento(
            tipo => 'IDOR', severidad => 'ALTA', usuario_id => snm.sp_EnviarExpediente.usuario_id,
            entidad => 'Expediente', entidad_id => id_txt);
        RAISE EXCEPTION 'Acceso denegado.';
    END IF;

    SELECT ruex, estado_id INTO ruex_exp, estado_exp
    FROM snm.Expediente
    WHERE snm.Expediente.expediente_id = snm.sp_EnviarExpediente.expediente_id
    FOR UPDATE;

    IF estado_exp NOT IN (1,3) THEN
        RAISE EXCEPTION 'El expediente no admite envio en su estado actual.';
    END IF;

    IF NOT priv.fn_ConsentimientoVigente(ruex_exp) THEN
        RAISE EXCEPTION 'Ley 81: consentimiento no vigente.';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM snm.ExpedienteRequisito er
        JOIN cat.Requisito r ON r.requisito_id = er.requisito_id
        WHERE er.expediente_id = snm.sp_EnviarExpediente.expediente_id
          AND r.origen = 'APORTADO'
          AND r.obligatorio = TRUE
          AND er.estado <> 'DOCUMENTO_VALIDO'
    ) THEN
        RAISE EXCEPTION 'Faltan requisitos documentales obligatorios o hay documentos vencidos.';
    END IF;

    INSERT INTO ext.ConsultaExterna(expediente_id, requisito_id, servicio_id)
    SELECT er.expediente_id, er.requisito_id, r.servicio_id
    FROM snm.ExpedienteRequisito er
    JOIN cat.Requisito r ON r.requisito_id = er.requisito_id
    WHERE er.expediente_id = snm.sp_EnviarExpediente.expediente_id
      AND r.origen = 'AUTOMATICO'
      AND NOT EXISTS (
          SELECT 1 FROM ext.ConsultaExterna c
          WHERE c.expediente_id = er.expediente_id
            AND c.requisito_id = er.requisito_id
      );

    UPDATE ext.ConsultaIntento i
    SET resultado = 'DESCARTADO',
        respondido_en = (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
        error_mensaje = 'Intento descartado por reenvio del expediente'
    FROM ext.ConsultaExterna c
    WHERE c.consulta_id = i.consulta_id
      AND c.expediente_id = snm.sp_EnviarExpediente.expediente_id
      AND c.resultado <> 'CUMPLE'
      AND i.resultado = 'EN_CURSO';

    UPDATE ext.ConsultaExterna
    SET resultado = 'PENDIENTE',
        respuesta_booleana = NULL,
        intentos = 0,
        respondida_en = NULL,
        sello_tiempo = NULL,
        firma_simulada = NULL
    WHERE expediente_id = snm.sp_EnviarExpediente.expediente_id
      AND resultado <> 'CUMPLE';

    UPDATE snm.ExpedienteRequisito er
    SET estado = 'PENDIENTE_VERIFICACION',
        actualizado_en = (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
    FROM ext.ConsultaExterna c
    WHERE c.expediente_id = er.expediente_id
      AND c.requisito_id = er.requisito_id
      AND er.expediente_id = snm.sp_EnviarExpediente.expediente_id
      AND c.resultado = 'PENDIENTE';

    obs := CASE WHEN estado_exp = 3
                THEN 'Reenvio tras subsanacion'
                ELSE 'Envio a validacion' END;

    CALL snm.sp_CambiarEstadoExpediente(
        expediente_id => snm.sp_EnviarExpediente.expediente_id, estado_nuevo => 2,
        usuario_id => snm.sp_EnviarExpediente.usuario_id, observacion => obs);

    CALL aud.sp_RegistrarEvento(
        tipo => 'EXPEDIENTE_ENVIADO', usuario_id => snm.sp_EnviarExpediente.usuario_id,
        ruex => ruex_exp, entidad => 'Expediente', entidad_id => id_txt);
END;
$$;

