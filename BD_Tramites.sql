CREATE OR REPLACE PROCEDURE snm.sp_CambiarEstadoExpediente(
    expediente_id BIGINT, estado_nuevo SMALLINT, usuario_id INTEGER DEFAULT NULL,
    observacion VARCHAR(500) DEFAULT NULL
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, cat, seg, priv, snm, ext, aud, met
AS $$
DECLARE
    anterior SMALLINT;
BEGIN
    SELECT estado_id INTO anterior
    FROM snm.Expediente
    WHERE snm.Expediente.expediente_id = snm.sp_CambiarEstadoExpediente.expediente_id
    FOR UPDATE;

    IF anterior IS NULL THEN
        RAISE EXCEPTION 'Expediente inexistente.';
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM (VALUES
            (1,2),(1,6),(2,3),(2,4),(2,5),(2,6),(3,2),(3,6)
        ) t(desde,hacia)
        WHERE t.desde = anterior AND t.hacia = estado_nuevo
    ) THEN
        RAISE EXCEPTION 'Transicion de estado del expediente no permitida.';
    END IF;

    INSERT INTO snm.HistorialEstadoExpediente(
        expediente_id, estado_anterior, estado_nuevo, usuario_id, observacion
    )
    VALUES (snm.sp_CambiarEstadoExpediente.expediente_id, anterior, snm.sp_CambiarEstadoExpediente.estado_nuevo, snm.sp_CambiarEstadoExpediente.usuario_id, snm.sp_CambiarEstadoExpediente.observacion);

    UPDATE snm.Expediente
    SET estado_id = snm.sp_CambiarEstadoExpediente.estado_nuevo,
        actualizado_en = (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
        enviado_en = CASE
            WHEN snm.sp_CambiarEstadoExpediente.estado_nuevo = 2 THEN (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
            ELSE enviado_en
        END
    WHERE snm.Expediente.expediente_id = snm.sp_CambiarEstadoExpediente.expediente_id;
END;
$$;

CREATE OR REPLACE PROCEDURE snm.sp_CrearExpedienteBorrador(
    usuario_id INTEGER, ruex VARCHAR(20), categoria_codigo VARCHAR(50),
    OUT expediente_id BIGINT, ip VARCHAR(45) DEFAULT NULL
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, cat, seg, priv, snm, ext, aud, met
AS $$
DECLARE
    cat_id SMALLINT;
    nuevo BIGINT;
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM snm.Extranjero
        WHERE snm.Extranjero.ruex = snm.sp_CrearExpedienteBorrador.ruex
          AND snm.Extranjero.usuario_id = snm.sp_CrearExpedienteBorrador.usuario_id
    ) THEN
        CALL aud.sp_RegistrarEvento(
            tipo => 'IDOR', severidad => 'ALTA', usuario_id => snm.sp_CrearExpedienteBorrador.usuario_id,
            ruex => snm.sp_CrearExpedienteBorrador.ruex, ip => snm.sp_CrearExpedienteBorrador.ip, detalle => 'Creacion de expediente sobre RUEX ajeno');
        RAISE EXCEPTION 'Acceso denegado.';
    END IF;

    IF NOT priv.fn_ConsentimientoVigente(snm.sp_CrearExpedienteBorrador.ruex) THEN
        RAISE EXCEPTION 'Ley 81: debe aceptar el aviso de privacidad antes de crear el expediente.';
    END IF;

    SELECT categoria_id INTO cat_id
    FROM cat.CategoriaMigratoria
    WHERE codigo = snm.sp_CrearExpedienteBorrador.categoria_codigo AND activa = TRUE;

    IF cat_id IS NULL THEN
        RAISE EXCEPTION 'Categoria migratoria inexistente o inactiva.';
    END IF;

    /* La unicidad parcial es la barrera definitiva contra carreras concurrentes. */
    IF EXISTS (
        SELECT 1 FROM snm.Expediente
        WHERE snm.Expediente.ruex = snm.sp_CrearExpedienteBorrador.ruex
          AND categoria_id = cat_id AND estado_id IN (1,2,3)
    ) THEN
        RAISE EXCEPTION 'Ya existe un expediente activo de este tipo para el RUEX.';
    END IF;

    INSERT INTO snm.Expediente(ruex, categoria_id, estado_id)
    VALUES (snm.sp_CrearExpedienteBorrador.ruex, cat_id, 1)
    RETURNING expediente_id INTO nuevo;

    INSERT INTO snm.HistorialEstadoExpediente(
        expediente_id, estado_anterior, estado_nuevo, usuario_id, observacion
    )
    VALUES (nuevo, NULL, 1, snm.sp_CrearExpedienteBorrador.usuario_id, 'Expediente creado en borrador');

    INSERT INTO snm.ExpedienteRequisito(expediente_id, requisito_id, estado)
    SELECT nuevo, r.requisito_id,
           CASE r.origen
             WHEN 'APORTADO' THEN 'PENDIENTE_CARGA'
             ELSE 'PENDIENTE_VERIFICACION'
           END
    FROM cat.Requisito r
    WHERE r.categoria_id = cat_id;

    CALL aud.sp_RegistrarEvento(
        tipo => 'EXPEDIENTE_CREADO', usuario_id => snm.sp_CrearExpedienteBorrador.usuario_id, ruex => snm.sp_CrearExpedienteBorrador.ruex,
        entidad => 'Expediente', entidad_id => nuevo::VARCHAR(20), ip => snm.sp_CrearExpedienteBorrador.ip);

    expediente_id := nuevo;
EXCEPTION
    WHEN unique_violation THEN
        RAISE EXCEPTION 'Ya existe un expediente activo de este tipo para el RUEX.';
END;
$$;

