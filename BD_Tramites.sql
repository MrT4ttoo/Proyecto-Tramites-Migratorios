CREATE OR REPLACE FUNCTION snm.tr_expediente_historial()
RETURNS trigger LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, cat, seg, priv, snm, ext, aud, met
AS $$
BEGIN
    IF NEW.estado_id IS DISTINCT FROM OLD.estado_id THEN
        IF NOT EXISTS (
            SELECT 1
            FROM snm.HistorialEstadoExpediente h
            WHERE h.expediente_id = NEW.expediente_id
              AND h.estado_anterior = OLD.estado_id
              AND h.estado_nuevo = NEW.estado_id
              AND h.historial_id = (
                  SELECT MAX(h2.historial_id)
                  FROM snm.HistorialEstadoExpediente h2
                  WHERE h2.expediente_id = NEW.expediente_id
              )
        ) THEN
            RAISE EXCEPTION USING ERRCODE = 'P0001',
                MESSAGE = 'Cambio de estado sin registro en snm.HistorialEstadoExpediente: use snm.sp_CambiarEstadoExpediente.';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION snm.tr_expreq_integridad()
RETURNS trigger LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, cat, seg, priv, snm, ext, aud, met
AS $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM snm.ExpedienteRequisito i
        JOIN snm.Expediente e ON e.expediente_id = i.expediente_id
        JOIN cat.Requisito r ON r.requisito_id = i.requisito_id
        LEFT JOIN snm.Documento d ON d.documento_id = i.documento_id
        WHERE i.expediente_id = NEW.expediente_id
          AND i.requisito_id = NEW.requisito_id
          AND (
              r.categoria_id <> e.categoria_id
              OR (i.documento_id IS NOT NULL AND
                  (d.ruex <> e.ruex OR r.origen <> 'APORTADO' OR d.tipo_documento_id <> r.tipo_documento_id))
          )
    ) THEN
        RAISE EXCEPTION USING ERRCODE = 'P0001',
            MESSAGE = 'Integridad: documento de otro RUEX/tipo o requisito ajeno a la categoria del expediente.';
    END IF;
    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION snm.tr_documento_insert()
RETURNS trigger LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, cat, seg, priv, snm, ext, aud, met
AS $$
DECLARE
    nueva_fecha DATE;
BEGIN
    IF NOT priv.fn_ConsentimientoVigente(NEW.ruex) THEN
        RAISE EXCEPTION USING ERRCODE = 'P0001',
            MESSAGE = 'Ley 81: no se puede persistir informacion sin consentimiento vigente del titular.';
    END IF;

    IF NEW.fecha_vencimiento IS NULL THEN
        SELECT CASE
                 WHEN t.vigencia_meses IS NOT NULL
                 THEN (NEW.fecha_emision + make_interval(months => t.vigencia_meses::integer))::date
               END
          INTO nueva_fecha
        FROM cat.TipoDocumento t
        WHERE t.tipo_documento_id = NEW.tipo_documento_id;

        IF nueva_fecha IS NOT NULL THEN
            NEW.fecha_vencimiento := nueva_fecha;
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

