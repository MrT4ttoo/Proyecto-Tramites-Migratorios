CREATE OR REPLACE FUNCTION priv.fn_AvisoVigente()
RETURNS INTEGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, cat, seg, priv, snm, ext, aud, met
AS $$
DECLARE
    hoy DATE := (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')::date;
    resultado INTEGER;
BEGIN
    SELECT aviso_id INTO resultado
    FROM priv.AvisoPrivacidad
    WHERE vigente_desde <= hoy
      AND (vigente_hasta IS NULL OR vigente_hasta >= hoy)
    ORDER BY vigente_desde DESC, aviso_id DESC
    LIMIT 1;
    RETURN resultado;
END;
$$;

CREATE OR REPLACE FUNCTION priv.fn_ConsentimientoVigente(p_ruex VARCHAR(20))
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, cat, seg, priv, snm, ext, aud, met
AS $$
DECLARE
    aviso_vigente INTEGER := priv.fn_AvisoVigente();
    aviso_ultimo INTEGER;
    aceptado BOOLEAN;
BEGIN
    SELECT c.aviso_id, c.aceptado
      INTO aviso_ultimo, aceptado
    FROM priv.Consentimiento c
    WHERE c.ruex = p_ruex
    ORDER BY c.fecha_hora DESC, c.consentimiento_id DESC
    LIMIT 1;

    RETURN COALESCE(aceptado, FALSE) AND aviso_ultimo = aviso_vigente;
END;
$$;

