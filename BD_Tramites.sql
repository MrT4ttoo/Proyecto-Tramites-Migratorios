CREATE OR REPLACE PROCEDURE seg.sp_ValidarSesion(
    token_hash BYTEA, OUT resultado REFCURSOR, minutos_inactividad SMALLINT DEFAULT 15
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, cat, seg, priv, snm, ext, aud, met
AS $$
DECLARE
    ahora TIMESTAMP(0) := (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')::timestamp(0);
BEGIN
    UPDATE seg.Sesion s
    SET ultima_actividad = ahora
    FROM seg.Usuario u
    WHERE u.usuario_id = s.usuario_id
      AND u.activo = TRUE
      AND s.token_hash = seg.sp_ValidarSesion.token_hash
      AND s.revocada = FALSE
      AND s.expira_en > ahora
