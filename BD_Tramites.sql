CREATE OR REPLACE PROCEDURE snm.sp_SugerirReutilizacion(
    usuario_id INTEGER, expediente_id BIGINT, OUT resultado REFCURSOR
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, cat, seg, priv, snm, ext, aud, met
AS $$
DECLARE
    id_txt VARCHAR(20) := expediente_id::VARCHAR(20);
    hoy DATE := (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')::date;
BEGIN
    IF NOT snm.fn_EsDuenoExpediente(snm.sp_SugerirReutilizacion.usuario_id, snm.sp_SugerirReutilizacion.expediente_id) THEN
        CALL aud.sp_RegistrarEvento(
            tipo => 'IDOR', severidad => 'ALTA', usuario_id => snm.sp_SugerirReutilizacion.usuario_id,
            entidad => 'Expediente', entidad_id => id_txt);
        RETURN;
    END IF;

    OPEN resultado FOR
    SELECT er.requisito_id, r.codigo AS codigo_requisito,
           d.documento_id, d.nombre_archivo, d.fecha_emision, d.fecha_vencimiento
    FROM snm.ExpedienteRequisito er
    JOIN cat.Requisito r
      ON r.requisito_id = er.requisito_id AND r.origen = 'APORTADO'
    JOIN snm.Expediente e ON e.expediente_id = er.expediente_id
