    OPEN resultado FOR
    SELECT s.usuario_id
    FROM seg.Sesion s
    JOIN seg.Usuario u ON u.usuario_id = s.usuario_id AND u.activo = TRUE
    WHERE s.token_hash = seg.sp_ValidarSesion.token_hash
      AND s.revocada = FALSE
