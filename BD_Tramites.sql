CREATE OR REPLACE PROCEDURE priv.sp_RegistrarConsentimiento(
    usuario_id INTEGER, ruex VARCHAR(20), version VARCHAR(20),
    ip_simulada VARCHAR(45), aceptado BOOLEAN DEFAULT TRUE
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, cat, seg, priv, snm, ext, aud, met
AS $$
DECLARE
    aviso INTEGER := priv.fn_AvisoVigente();
    ultimo_aviso INTEGER;
    ultimo_aceptado BOOLEAN;
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM snm.Extranjero
        WHERE snm.Extranjero.ruex = priv.sp_RegistrarConsentimiento.ruex
          AND snm.Extranjero.usuario_id = priv.sp_RegistrarConsentimiento.usuario_id
    ) THEN
        CALL aud.sp_RegistrarEvento(
            tipo => 'ACCESO_DENEGADO', severidad => 'ALTA',
            usuario_id => priv.sp_RegistrarConsentimiento.usuario_id, ruex => priv.sp_RegistrarConsentimiento.ruex,
            detalle => 'Consentimiento sobre RUEX ajeno');
        RAISE EXCEPTION 'Acceso denegado.';
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM priv.AvisoPrivacidad
        WHERE aviso_id = aviso AND priv.AvisoPrivacidad.version = priv.sp_RegistrarConsentimiento.version
    ) THEN
        RAISE EXCEPTION 'Version del aviso de privacidad inexistente o no es la vigente.';
    END IF;

    SELECT c.aviso_id, c.aceptado
      INTO ultimo_aviso, ultimo_aceptado
    FROM priv.Consentimiento c
    WHERE c.ruex = priv.sp_RegistrarConsentimiento.ruex
    ORDER BY c.fecha_hora DESC, c.consentimiento_id DESC
    LIMIT 1
    FOR UPDATE;

    IF ultimo_aviso = aviso AND ultimo_aceptado IS NOT DISTINCT FROM priv.sp_RegistrarConsentimiento.aceptado THEN
        RETURN;
    END IF;

    INSERT INTO priv.Consentimiento(ruex, aviso_id, aceptado, ip_simulada)
    VALUES (priv.sp_RegistrarConsentimiento.ruex, aviso, priv.sp_RegistrarConsentimiento.aceptado, priv.sp_RegistrarConsentimiento.ip_simulada);

    CALL aud.sp_RegistrarEvento(
        tipo => 'CONSENTIMIENTO', usuario_id => priv.sp_RegistrarConsentimiento.usuario_id, ruex => priv.sp_RegistrarConsentimiento.ruex,
        entidad => 'AvisoPrivacidad', entidad_id => priv.sp_RegistrarConsentimiento.version,
        ip => priv.sp_RegistrarConsentimiento.ip_simulada,
        detalle => 'Consentimiento registrado (aceptado=1) o revocado (0)');
END;
$$;

