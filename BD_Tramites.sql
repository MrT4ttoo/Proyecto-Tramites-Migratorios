/* ======================= CONSULTAS BIG (SIMULADAS) =======================
   MODELO: "consulta logica" vs "intentos"
   - ext.ConsultaExterna  = UNA consulta logica por (expediente, requisito) [UQ_Consulta_logica].
       Su correlation_id identifica la consulta logica y es estable entre reintentos.
       intentos     = fallos TECNICOS (indisponibilidad) acumulados en el ciclo vigente.
       max_intentos = tope de fallos tecnicos antes de pasar a INDISPONIBILIDAD_TECNICA.
       Un resultado funcional (CUMPLE / NO_CUMPLE) NUNCA suma a intentos.
   - ext.ConsultaIntento  = historial de cada llamada al adaptador. Cada intento tiene su propio
       correlation_id (UNIQUE): es la llave de idempotencia de la RESPUESTA. Una respuesta repetida
       no se procesa dos veces.
   Ciclo de resultado de la consulta logica:
       PENDIENTE --(CUMPLE|NO_CUMPLE)--> final del ciclo
       PENDIENTE --(fallo tecnico, intentos < max)--> PENDIENTE (reintento)
       PENDIENTE --(fallo tecnico, intentos = max)--> INDISPONIBILIDAD_TECNICA
       INDISPONIBILIDAD_TECNICA --ext.sp_ReintentarConsulta--> PENDIENTE (intentos = 0)
       NO_CUMPLE / INDISPONIBILIDAD --reenvio tras subsanacion--> PENDIENTE (intentos = 0)
   ==================================================================== */
CREATE TABLE ext.ConsultaExterna(
    consulta_id BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT PK_Consulta PRIMARY KEY,
    correlation_id UUID NOT NULL CONSTRAINT DF_Consulta_corr DEFAULT public.gen_random_uuid() CONSTRAINT UQ_Consulta_corr UNIQUE,
    expediente_id BIGINT NOT NULL,
    requisito_id INT NOT NULL,
    servicio_id SMALLINT NOT NULL CONSTRAINT FK_Consulta_Servicio REFERENCES cat.ServicioExterno(servicio_id),
    parametros_hash BYTEA NULL,           -- hash de los parametros; no se guardan datos del origen
    resultado VARCHAR(25) NOT NULL DEFAULT 'PENDIENTE' CONSTRAINT CK_Consulta_res CHECK (resultado IN ('PENDIENTE','CUMPLE','NO_CUMPLE','INDISPONIBILIDAD_TECNICA')),
    respuesta_booleana BOOLEAN NULL,               -- 1 validado / 0 rechazado (minimizacion)
    intentos SMALLINT NOT NULL DEFAULT 0,       -- fallos tecnicos del ciclo vigente (NO cuenta CUMPLE/NO_CUMPLE)
    max_intentos SMALLINT NOT NULL DEFAULT 3,
    solicitada_en TIMESTAMP(3) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    respondida_en TIMESTAMP(3) NULL,
    sello_tiempo TIMESTAMP(3) NULL,
    firma_simulada BYTEA NULL,
    CONSTRAINT FK_Consulta_ExpReq FOREIGN KEY (expediente_id, requisito_id)
        REFERENCES snm.ExpedienteRequisito(expediente_id, requisito_id),
    CONSTRAINT UQ_Consulta_logica UNIQUE (expediente_id, requisito_id),   -- una consulta logica por requisito
    CONSTRAINT CK_Consulta_bool CHECK (
        (resultado='CUMPLE' AND respuesta_booleana = TRUE) OR
        (resultado='NO_CUMPLE' AND respuesta_booleana = FALSE) OR
        (resultado IN ('PENDIENTE','INDISPONIBILIDAD_TECNICA') AND respuesta_booleana IS NULL)),
    -- Invariante anti-estados contradictorios: INDISPONIBILIDAD_TECNICA <=> reintentos agotados
    CONSTRAINT CK_Consulta_intentos CHECK (max_intentos >= 1 AND (
        (resultado = 'INDISPONIBILIDAD_TECNICA' AND intentos >= max_intentos) OR
        (resultado <> 'INDISPONIBILIDAD_TECNICA' AND intentos < max_intentos))),
    CONSTRAINT CK_Consulta_respondida CHECK (
        (resultado IN ('CUMPLE','NO_CUMPLE') AND respondida_en IS NOT NULL) OR
        (resultado IN ('PENDIENTE','INDISPONIBILIDAD_TECNICA') AND respondida_en IS NULL)));
-- Cola de trabajo del adaptador: solo consultas pendientes
CREATE INDEX IX_Consulta_pendiente ON ext.ConsultaExterna(solicitada_en)
    INCLUDE (expediente_id, requisito_id, servicio_id, intentos, max_intentos) WHERE resultado = 'PENDIENTE';

CREATE TABLE ext.ConsultaIntento(          -- historial de intentos de la consulta logica (nunca se borra)
    intento_id BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT PK_ConsultaIntento PRIMARY KEY,
    consulta_id BIGINT NOT NULL CONSTRAINT FK_Intento_Consulta REFERENCES ext.ConsultaExterna(consulta_id),
    nro_intento SMALLINT NOT NULL,             -- consecutivo por consulta, se conserva entre ciclos
    correlation_id UUID NOT NULL CONSTRAINT DF_Intento_corr DEFAULT public.gen_random_uuid() CONSTRAINT UQ_Intento_corr UNIQUE,
    registrado_en TIMESTAMP(3) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),   -- apertura del intento
    respondido_en TIMESTAMP(3) NULL,                                -- cierre (respuesta o descarte)
    codigo_http SMALLINT NULL,
    -- EN_CURSO: enviado, sin respuesta | CUMPLE/NO_CUMPLE: respuesta funcional
    -- INDISPONIBILIDAD_TECNICA: fallo tecnico de ESTE intento | DESCARTADO: sin efecto (respuesta tardia / reenvio)
    resultado VARCHAR(25) NOT NULL CONSTRAINT CK_Intento_res CHECK (resultado IN ('EN_CURSO','CUMPLE','NO_CUMPLE','INDISPONIBILIDAD_TECNICA','DESCARTADO')),
    error_mensaje VARCHAR(400) NULL,
    CONSTRAINT UQ_Intento UNIQUE (consulta_id, nro_intento),
    CONSTRAINT CK_Intento_cierre CHECK ((resultado = 'EN_CURSO' AND respondido_en IS NULL) OR (resultado <> 'EN_CURSO' AND respondido_en IS NOT NULL)));
-- A lo sumo un intento abierto por consulta logica
CREATE UNIQUE INDEX UX_Intento_EnCurso ON ext.ConsultaIntento(consulta_id) WHERE resultado = 'EN_CURSO';

