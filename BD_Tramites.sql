CREATE OR REPLACE PROCEDURE seg.sp_RegistrarIntentoLogin(
    correo VARCHAR(254), ip VARCHAR(45), exitoso BOOLEAN, OUT estado_resultado VARCHAR(25)
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, cat, seg, priv, snm, ext, aud, met
AS $$
DECLARE
    ahora TIMESTAMP(0) := (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')::timestamp(0);
    uid INTEGER;
    bloq TIMESTAMP(0);
    fallos SMALLINT;
    estado VARCHAR(25);
BEGIN
    SELECT usuario_id, bloqueado_hasta, intentos_fallidos
      INTO uid, bloq, fallos
    FROM seg.Usuario
    WHERE seg.Usuario.correo = seg.sp_RegistrarIntentoLogin.correo
      AND activo = TRUE
    FOR UPDATE;

    IF (SELECT COUNT(*) FROM seg.IntentoLogin
        WHERE ip_origen = seg.sp_RegistrarIntentoLogin.ip
          AND exitoso = FALSE
          AND fecha_utc > ahora - INTERVAL '10 minutes') >= 10 THEN

        INSERT INTO seg.IntentoLogin(usuario_id, correo_intentado, ip_origen, exitoso)
        VALUES (uid, seg.sp_RegistrarIntentoLogin.correo, seg.sp_RegistrarIntentoLogin.ip, FALSE);
        CALL aud.sp_RegistrarEvento(
            tipo => 'LOGIN_LIMITE_TASA', severidad => 'MEDIA',
            usuario_id => uid, ip => seg.sp_RegistrarIntentoLogin.ip, detalle => 'Rate limiting por IP');
        estado := 'LIMITE_TASA';

    ELSIF bloq IS NOT NULL AND bloq > ahora THEN
        INSERT INTO seg.IntentoLogin(usuario_id, correo_intentado, ip_origen, exitoso)
        VALUES (uid, seg.sp_RegistrarIntentoLogin.correo, seg.sp_RegistrarIntentoLogin.ip, FALSE);
        CALL aud.sp_RegistrarEvento(
            tipo => 'LOGIN_BLOQUEADO', severidad => 'MEDIA',
            usuario_id => uid, ip => seg.sp_RegistrarIntentoLogin.ip);
        estado := 'BLOQUEADO';

    ELSIF uid IS NULL THEN
        INSERT INTO seg.IntentoLogin(usuario_id, correo_intentado, ip_origen, exitoso)
        VALUES (NULL, seg.sp_RegistrarIntentoLogin.correo, seg.sp_RegistrarIntentoLogin.ip, FALSE);
        estado := 'CREDENCIALES_INVALIDAS';

    ELSIF seg.sp_RegistrarIntentoLogin.exitoso THEN
        INSERT INTO seg.IntentoLogin(usuario_id, correo_intentado, ip_origen, exitoso)
        VALUES (uid, seg.sp_RegistrarIntentoLogin.correo, seg.sp_RegistrarIntentoLogin.ip, TRUE);
        UPDATE seg.Usuario
        SET intentos_fallidos = 0, bloqueado_hasta = NULL, ultimo_acceso = ahora
        WHERE usuario_id = uid;
        CALL aud.sp_RegistrarEvento(
            tipo => 'LOGIN_OK', usuario_id => uid, ip => seg.sp_RegistrarIntentoLogin.ip);
        estado := 'OK';

    ELSE
        INSERT INTO seg.IntentoLogin(usuario_id, correo_intentado, ip_origen, exitoso)
        VALUES (uid, seg.sp_RegistrarIntentoLogin.correo, seg.sp_RegistrarIntentoLogin.ip, FALSE);
        fallos := COALESCE(fallos, 0) + 1;

        IF fallos >= 3 THEN
            UPDATE seg.Usuario
            SET intentos_fallidos = 0,
                bloqueado_hasta = ahora + INTERVAL '15 minutes'
            WHERE usuario_id = uid;
            CALL aud.sp_RegistrarEvento(
                tipo => 'LOGIN_BLOQUEO', severidad => 'MEDIA',
                usuario_id => uid, ip => seg.sp_RegistrarIntentoLogin.ip,
                detalle => '3 intentos fallidos consecutivos');
            estado := 'BLOQUEADO';
        ELSE
            UPDATE seg.Usuario SET intentos_fallidos = fallos WHERE usuario_id = uid;
            estado := 'CREDENCIALES_INVALIDAS';
        END IF;
    END IF;

    estado_resultado := estado;
END;
$$;

