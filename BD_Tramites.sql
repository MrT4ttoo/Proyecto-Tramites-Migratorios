CREATE OR REPLACE PROCEDURE snm.sp_PanelFuncionario(funcionario_id INTEGER, OUT resumen_cursor REFCURSOR, OUT detalle_cursor REFCURSOR)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, cat, seg, priv, snm, ext, aud, met
AS $$
BEGIN
    IF NOT seg.fn_TieneRol(snm.sp_PanelFuncionario.funcionario_id, 'FUNCIONARIO_REVISOR')
       OR NOT seg.fn_EnJornada(snm.sp_PanelFuncionario.funcionario_id) THEN
        CALL aud.sp_RegistrarEvento(
            tipo => 'ACCESO_DENEGADO', severidad => 'MEDIA',
            usuario_id => snm.sp_PanelFuncionario.funcionario_id, entidad => 'PanelFuncionario',
            detalle => 'Sin rol o fuera de jornada');
        RAISE EXCEPTION 'Acceso denegado.';
    END IF;

    OPEN resumen_cursor FOR
    SELECT e.expediente_id, e.codigo_expediente, e.ruex,
           c.nombre AS categoria, e.enviado_en,
           COUNT(*) AS total_requisitos,
           SUM(CASE WHEN er.estado IN ('DOCUMENTO_VALIDO','VERIFICADO_FUENTE') THEN 1 ELSE 0 END) AS verificados,
           SUM(CASE WHEN er.estado IN ('NO_CUMPLE','DOCUMENTO_VENCIDO') THEN 1 ELSE 0 END) AS discrepancias,
           SUM(CASE WHEN er.estado = 'INDISPONIBILIDAD_TECNICA' THEN 1 ELSE 0 END) AS indisponibles,
           SUM(CASE WHEN er.estado = 'PENDIENTE_VERIFICACION' THEN 1 ELSE 0 END) AS pendientes
    FROM snm.Expediente e
    JOIN cat.CategoriaMigratoria c ON c.categoria_id = e.categoria_id
    JOIN snm.ExpedienteRequisito er ON er.expediente_id = e.expediente_id
    WHERE e.estado_id = 2 AND e.funcionario_id = snm.sp_PanelFuncionario.funcionario_id
    GROUP BY e.expediente_id, e.codigo_expediente, e.ruex, c.nombre, e.enviado_en
    ORDER BY e.enviado_en;

    OPEN detalle_cursor FOR
    SELECT v.expediente_id, v.codigo_requisito, v.descripcion,
           v.entidad_externa, v.etiqueta, v.semaforo, v.resultado_consulta,
           v.consulta_correlation_id, v.intentos_consulta, v.max_intentos_consulta
    FROM snm.vw_RequisitosExpediente v
    JOIN snm.Expediente e ON e.expediente_id = v.expediente_id
    WHERE e.estado_id = 2
      AND e.funcionario_id = snm.sp_PanelFuncionario.funcionario_id
      AND v.origen = 'AUTOMATICO'
    ORDER BY v.expediente_id, v.orden;
END;
$$;

CREATE OR REPLACE PROCEDURE snm.sp_RegistrarDecision(
    funcionario_id INTEGER, expediente_id BIGINT, decision VARCHAR(25),
    observacion VARCHAR(500) DEFAULT NULL
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, cat, seg, priv, snm, ext, aud, met
AS $$
DECLARE
    id_txt VARCHAR(20) := expediente_id::VARCHAR(20);
    ruex_exp VARCHAR(20);
    estado SMALLINT;
    nuevo SMALLINT;
BEGIN
    IF snm.sp_RegistrarDecision.decision NOT IN ('APROBAR','SOLICITAR_SUBSANACION','RECHAZAR') THEN
        RAISE EXCEPTION 'Decision invalida.';
    END IF;

    IF snm.sp_RegistrarDecision.decision <> 'APROBAR' AND snm.sp_RegistrarDecision.observacion IS NULL THEN
        RAISE EXCEPTION 'Se requiere observacion para subsanar o rechazar.';
    END IF;

    IF NOT seg.fn_TieneRol(snm.sp_RegistrarDecision.funcionario_id, 'FUNCIONARIO_REVISOR')
       OR NOT seg.fn_EnJornada(snm.sp_RegistrarDecision.funcionario_id)
       OR NOT EXISTS (
           SELECT 1 FROM snm.Expediente
           WHERE snm.Expediente.expediente_id = snm.sp_RegistrarDecision.expediente_id
             AND funcionario_id = snm.sp_RegistrarDecision.funcionario_id
       ) THEN
        CALL aud.sp_RegistrarEvento(
            tipo => 'ACCESO_DENEGADO', severidad => 'ALTA',
            usuario_id => snm.sp_RegistrarDecision.funcionario_id, entidad => 'Expediente',
            entidad_id => id_txt, detalle => 'Decision no autorizada');
        RAISE EXCEPTION 'Acceso denegado.';
    END IF;

    nuevo := CASE snm.sp_RegistrarDecision.decision
               WHEN 'APROBAR' THEN 4
               WHEN 'SOLICITAR_SUBSANACION' THEN 3
               ELSE 5
             END;

    SELECT ruex, estado_id INTO ruex_exp, estado
    FROM snm.Expediente
    WHERE snm.Expediente.expediente_id = snm.sp_RegistrarDecision.expediente_id
    FOR UPDATE;

    IF estado IS NULL OR estado <> 2 THEN
        RAISE EXCEPTION 'El expediente no esta En Validacion.';
    END IF;

    IF snm.sp_RegistrarDecision.decision <> 'RECHAZAR' AND NOT priv.fn_ConsentimientoVigente(ruex_exp) THEN
        RAISE EXCEPTION 'Ley 81: consentimiento no vigente.';
    END IF;

    IF snm.sp_RegistrarDecision.decision = 'APROBAR' AND EXISTS (
        SELECT 1
        FROM snm.ExpedienteRequisito er
        JOIN cat.Requisito r ON r.requisito_id = er.requisito_id
        WHERE er.expediente_id = snm.sp_RegistrarDecision.expediente_id
          AND r.obligatorio = TRUE
          AND er.estado NOT IN ('DOCUMENTO_VALIDO','VERIFICADO_FUENTE')
    ) THEN
        RAISE EXCEPTION 'No se puede aprobar: hay requisitos obligatorios sin verificar.';
    END IF;

    INSERT INTO snm.DecisionExpediente(
        expediente_id, funcionario_id, decision, observacion)
    VALUES (snm.sp_RegistrarDecision.expediente_id, snm.sp_RegistrarDecision.funcionario_id, snm.sp_RegistrarDecision.decision, snm.sp_RegistrarDecision.observacion);

    CALL snm.sp_CambiarEstadoExpediente(
        expediente_id => snm.sp_RegistrarDecision.expediente_id, estado_nuevo => nuevo,
        usuario_id => snm.sp_RegistrarDecision.funcionario_id, observacion => snm.sp_RegistrarDecision.observacion);

    CALL aud.sp_RegistrarEvento(
        tipo => 'DECISION', usuario_id => snm.sp_RegistrarDecision.funcionario_id,
        ruex => ruex_exp, entidad => 'Expediente',
        entidad_id => id_txt, detalle => snm.sp_RegistrarDecision.decision);
END;
$$;

