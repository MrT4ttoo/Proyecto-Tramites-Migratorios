CREATE OR REPLACE PROCEDURE ext.sp_IniciarIntentoConsulta(
    correlation_id UUID, OUT intento_correlation_id UUID, OUT nro_intento SMALLINT
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, cat, seg, priv, snm, ext, aud, met
AS $$
DECLARE
    cid BIGINT;
    exp BIGINT;
    ruex_exp VARCHAR(20);
    estado_exp SMALLINT;
    res VARCHAR(25);
    icorr UUID;
    nro SMALLINT;
BEGIN
    SELECT expediente_id INTO exp
    FROM ext.ConsultaExterna
    WHERE ext.ConsultaExterna.correlation_id = ext.sp_IniciarIntentoConsulta.correlation_id;

    IF exp IS NULL THEN
        RAISE EXCEPTION 'correlation_id inexistente.';
    END IF;

    SELECT ruex, estado_id INTO ruex_exp, estado_exp
    FROM snm.Expediente
    WHERE expediente_id = exp
    FOR UPDATE;

    SELECT consulta_id, resultado INTO cid, res
    FROM ext.ConsultaExterna
    WHERE ext.ConsultaExterna.correlation_id = ext.sp_IniciarIntentoConsulta.correlation_id
    FOR UPDATE;

    IF res <> 'PENDIENTE' OR estado_exp <> 2 THEN
        RAISE EXCEPTION 'La consulta no admite nuevos intentos en su estado actual.';
    END IF;

    IF NOT priv.fn_ConsentimientoVigente(ruex_exp) THEN
        RAISE EXCEPTION 'Ley 81: no se pueden consultar entidades externas sin consentimiento vigente.';
    END IF;

    SELECT i.correlation_id, i.nro_intento INTO icorr, nro
    FROM ext.ConsultaIntento i
    WHERE i.consulta_id = cid AND i.resultado = 'EN_CURSO'
    LIMIT 1;

    IF icorr IS NULL THEN
        icorr := public.gen_random_uuid();
        SELECT COALESCE(MAX(nro_intento),0) + 1 INTO nro
        FROM ext.ConsultaIntento
        WHERE consulta_id = cid;

        INSERT INTO ext.ConsultaIntento(
            consulta_id, nro_intento, correlation_id, resultado
        )
        VALUES (cid, nro, icorr, 'EN_CURSO');
    END IF;

    intento_correlation_id := icorr;
    nro_intento := nro;
END;
$$;

CREATE OR REPLACE PROCEDURE ext.sp_RegistrarResultadoConsulta(
    correlation_id UUID, resultado VARCHAR(25),
    OUT estado_resultado VARCHAR(15),
    codigo_http SMALLINT DEFAULT NULL,
    error VARCHAR(400) DEFAULT NULL,
    firma_simulada BYTEA DEFAULT NULL
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, cat, seg, priv, snm, ext, aud, met
AS $$
DECLARE
    cid BIGINT;
    exp BIGINT;
    req INTEGER;
    ruex_exp VARCHAR(20);
    estado_exp SMALLINT;
    res_consulta VARCHAR(25);
    v_intentos SMALLINT;
    v_max_intentos SMALLINT;
    res_intento VARCHAR(25);
    estado_out VARCHAR(15) := 'REGISTRADA';
    id_txt VARCHAR(60) := ext.sp_RegistrarResultadoConsulta.correlation_id::VARCHAR(36);
BEGIN
    IF ext.sp_RegistrarResultadoConsulta.resultado NOT IN ('CUMPLE','NO_CUMPLE','INDISPONIBILIDAD_TECNICA') THEN
        RAISE EXCEPTION 'Resultado invalido.';
    END IF;

    SELECT i.consulta_id, c.expediente_id, c.requisito_id
      INTO cid, exp, req
    FROM ext.ConsultaIntento i
    JOIN ext.ConsultaExterna c ON c.consulta_id = i.consulta_id
    WHERE i.correlation_id = ext.sp_RegistrarResultadoConsulta.correlation_id;

    IF cid IS NULL THEN
        RAISE EXCEPTION 'correlation_id inexistente.';
    END IF;

    SELECT ruex, estado_id INTO ruex_exp, estado_exp
    FROM snm.Expediente
    WHERE expediente_id = exp
    FOR UPDATE;

    SELECT c.resultado, c.intentos, c.max_intentos
      INTO res_consulta, v_intentos, v_max_intentos
    FROM ext.ConsultaExterna c
    WHERE c.consulta_id = cid
    FOR UPDATE;

    SELECT i.resultado INTO res_intento
    FROM ext.ConsultaIntento i
    WHERE ext.ConsultaIntento.correlation_id = ext.sp_RegistrarResultadoConsulta.correlation_id
    FOR UPDATE;

    IF res_intento <> 'EN_CURSO' THEN
        estado_resultado := 'YA_PROCESADA';
        RETURN;
    END IF;

    IF estado_exp <> 2 OR res_consulta <> 'PENDIENTE' THEN
        UPDATE ext.ConsultaIntento
        SET resultado = 'DESCARTADO',
            respondido_en = (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
            codigo_http = ext.sp_RegistrarResultadoConsulta.codigo_http,
            error_mensaje = 'Respuesta tardia: la consulta o el expediente ya no esperaban respuesta'
        WHERE ext.ConsultaIntento.correlation_id = ext.sp_RegistrarResultadoConsulta.correlation_id;

        estado_resultado := 'SIN_EFECTO';
        RETURN;
    END IF;

    IF NOT priv.fn_ConsentimientoVigente(ruex_exp) THEN
        RAISE EXCEPTION 'Ley 81: no se pueden registrar resultados externos sin consentimiento vigente.';
    END IF;

    UPDATE ext.ConsultaIntento
    SET resultado = ext.sp_RegistrarResultadoConsulta.resultado,
        respondido_en = (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
        codigo_http = ext.sp_RegistrarResultadoConsulta.codigo_http,
        error_mensaje = ext.sp_RegistrarResultadoConsulta.error
    WHERE ext.ConsultaIntento.correlation_id = ext.sp_RegistrarResultadoConsulta.correlation_id;

    IF ext.sp_RegistrarResultadoConsulta.resultado IN ('CUMPLE','NO_CUMPLE') THEN
        UPDATE ext.ConsultaExterna
        SET resultado = ext.sp_RegistrarResultadoConsulta.resultado,
            respuesta_booleana = (ext.sp_RegistrarResultadoConsulta.resultado = 'CUMPLE'),
            respondida_en = (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
            sello_tiempo = (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
            firma_simulada = ext.sp_RegistrarResultadoConsulta.firma_simulada
        WHERE consulta_id = cid;

        UPDATE snm.ExpedienteRequisito
        SET estado = CASE
                       WHEN ext.sp_RegistrarResultadoConsulta.resultado = 'CUMPLE'
                       THEN 'VERIFICADO_FUENTE'
                       ELSE 'NO_CUMPLE'
                     END,
            actualizado_en = (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
        WHERE expediente_id = exp AND requisito_id = req;
    ELSE
        v_intentos := v_intentos + 1;

        IF v_intentos >= v_max_intentos THEN
            UPDATE ext.ConsultaExterna
            SET resultado = 'INDISPONIBILIDAD_TECNICA',
                intentos = v_intentos
            WHERE consulta_id = cid;

            UPDATE snm.ExpedienteRequisito
            SET estado = 'INDISPONIBILIDAD_TECNICA',
                actualizado_en = (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
            WHERE expediente_id = exp AND requisito_id = req;
        ELSE
            UPDATE ext.ConsultaExterna
            SET intentos = v_intentos
            WHERE consulta_id = cid;
        END IF;
    END IF;

    CALL aud.sp_RegistrarEvento(
        tipo => 'CONSULTA_API', ruex => ruex_exp,
        entidad => 'ConsultaIntento', entidad_id => id_txt,
        detalle => ext.sp_RegistrarResultadoConsulta.resultado);

    estado_resultado := estado_out;
END;
$$;

CREATE OR REPLACE PROCEDURE ext.sp_ReintentarConsulta(
    usuario_id INTEGER, correlation_id UUID, OUT estado_resultado VARCHAR(25), ip VARCHAR(45) DEFAULT NULL
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, cat, seg, priv, snm, ext, aud, met
AS $$
DECLARE
    cid BIGINT;
    exp BIGINT;
    req INTEGER;
    ruex_exp VARCHAR(20);
    func INTEGER;
    estado_exp SMALLINT;
    res VARCHAR(25);
    id_txt VARCHAR(60) := ext.sp_ReintentarConsulta.correlation_id::VARCHAR(36);
BEGIN
    SELECT consulta_id, expediente_id, requisito_id
      INTO cid, exp, req
    FROM ext.ConsultaExterna
    WHERE ext.ConsultaExterna.correlation_id = ext.sp_ReintentarConsulta.correlation_id;

    SELECT funcionario_id INTO func
    FROM snm.Expediente
    WHERE expediente_id = exp;

    IF cid IS NULL
       OR NOT (
           seg.fn_TieneRol(ext.sp_ReintentarConsulta.usuario_id, 'ADMINISTRADOR')
           OR (seg.fn_TieneRol(ext.sp_ReintentarConsulta.usuario_id, 'FUNCIONARIO_REVISOR')
               AND func = ext.sp_ReintentarConsulta.usuario_id
               AND seg.fn_EnJornada(ext.sp_ReintentarConsulta.usuario_id))
       ) THEN
        CALL aud.sp_RegistrarEvento(
            tipo => 'ACCESO_DENEGADO', severidad => 'ALTA',
            usuario_id => ext.sp_ReintentarConsulta.usuario_id, ip => ext.sp_ReintentarConsulta.ip,
            entidad => 'ConsultaExterna', entidad_id => id_txt,
            detalle => 'Reintento de consulta no autorizado');
        RAISE EXCEPTION 'Acceso denegado.';
    END IF;

    SELECT ruex, estado_id INTO ruex_exp, estado_exp
    FROM snm.Expediente
    WHERE expediente_id = exp
    FOR UPDATE;

    SELECT resultado INTO res
    FROM ext.ConsultaExterna
    WHERE consulta_id = cid
    FOR UPDATE;

    IF estado_exp <> 2 OR res <> 'INDISPONIBILIDAD_TECNICA' THEN
        RAISE EXCEPTION 'Solo se puede reintentar una consulta en INDISPONIBILIDAD_TECNICA de un expediente En Validacion.';
    END IF;

    IF NOT priv.fn_ConsentimientoVigente(ruex_exp) THEN
        RAISE EXCEPTION 'Ley 81: consentimiento no vigente.';
    END IF;

    UPDATE ext.ConsultaExterna
    SET resultado = 'PENDIENTE',
        respuesta_booleana = NULL,
        intentos = 0,
        respondida_en = NULL,
        sello_tiempo = NULL,
        firma_simulada = NULL
    WHERE consulta_id = cid;

    UPDATE snm.ExpedienteRequisito
    SET estado = 'PENDIENTE_VERIFICACION',
        actualizado_en = (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
    WHERE expediente_id = exp
      AND requisito_id = req
      AND estado = 'INDISPONIBILIDAD_TECNICA';

    CALL aud.sp_RegistrarEvento(
        tipo => 'CONSULTA_REINTENTO', usuario_id => ext.sp_ReintentarConsulta.usuario_id,
        ruex => ruex_exp, ip => ext.sp_ReintentarConsulta.ip, entidad => 'ConsultaExterna',
        entidad_id => id_txt,
        detalle => 'Reintento manual tras indisponibilidad tecnica');

    estado_resultado := 'REINTENTO_PROGRAMADO';
END;
$$;

